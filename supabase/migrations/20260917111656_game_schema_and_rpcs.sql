create or replace function public.skip_question(p_code text,p_token uuid)
returns void language plpgsql security definer set search_path='' as $$
declare me public.players; r public.rooms; q int;
begin
  me:=public._player(p_code,p_token); if me.id is null then raise exception 'Session expirée. Rejoins la partie à nouveau.'; end if;
  select * into r from public.rooms where id=me.room_id for update;
  if r.reader_id<>me.id then raise exception 'Seul le lecteur peut changer la question.'; end if;
  if r.status<>'answering' then raise exception 'Trop tard pour changer la question.'; end if;
  if r.skips_used>=3 then raise exception 'Tu as déjà changé 3 fois de question.'; end if;
  if exists(select 1 from public.submissions where room_id=r.id and round=r.round) then raise exception 'Quelqu''un a déjà répondu à cette question.'; end if;
  q:=public._draw_question(r.id); update public.rooms set question_id=q,skips_used=skips_used+1,updated_at=now() where id=r.id;
end $$;

