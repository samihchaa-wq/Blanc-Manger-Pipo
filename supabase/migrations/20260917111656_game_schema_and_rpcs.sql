-- SANITIZED SQUASHED BASELINE
--
-- The original production migration with this version predates repository
-- versioning. This file intentionally represents the current production schema
-- without secret app_settings values. Later historical versions are retained as
-- no-op markers so Supabase migration versions stay aligned with production.

create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.questions (
  id integer generated by default as identity primary key,
  text text not null,
  created_at timestamptz not null default now(),
  added_by text,
  deleted_at timestamptz
);

create table if not exists public.answers (
  id integer generated by default as identity primary key,
  text text not null,
  created_at timestamptz not null default now(),
  added_by text,
  deleted_at timestamptz
);

create table if not exists public.rooms (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  status text not null default 'lobby' check (status in ('lobby','answering','judging','reveal','finished')),
  host_id uuid,
  reader_id uuid,
  question_id integer references public.questions(id),
  round integer not null default 0,
  winner_id uuid,
  winning_submission_id uuid,
  target_score integer not null default 5 check (target_score in (3,5,7,10)),
  hand_size integer not null default 7,
  used_questions integer[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  skips_used integer not null default 0,
  reward_used boolean not null default false,
  reward_kind text,
  reward_text text,
  created_by_hash text
);

create table if not exists public.players (
  id uuid primary key default gen_random_uuid(),
  room_id uuid not null references public.rooms(id) on delete cascade,
  name text not null,
  token uuid not null default gen_random_uuid(),
  score integer not null default 0,
  seat integer not null,
  active boolean not null default true,
  last_seen timestamptz not null default now(),
  discard_round integer not null default 0,
  created_at timestamptz not null default now(),
  joined_by_hash text,
  unique(room_id, seat)
);

create table if not exists public.hands (
  player_id uuid not null references public.players(id) on delete cascade,
  answer_id integer not null references public.answers(id),
  room_id uuid not null references public.rooms(id) on delete cascade,
  primary key(player_id, answer_id)
);

create table if not exists public.used_answers (
  room_id uuid not null references public.rooms(id) on delete cascade,
  answer_id integer not null references public.answers(id),
  primary key(room_id, answer_id)
);

create table if not exists public.submissions (
  id uuid primary key default gen_random_uuid(),
  room_id uuid not null references public.rooms(id) on delete cascade,
  round integer not null,
  player_id uuid not null references public.players(id) on delete cascade,
  answer_id integer not null references public.answers(id),
  sort_key double precision not null default random(),
  unique(room_id, round, player_id)
);

create table if not exists public.app_settings (
  key text primary key,
  value text not null
);

create unique index if not exists questions_text_uniq on public.questions(lower(text));
create unique index if not exists answers_text_uniq on public.answers(lower(text));
create index if not exists rooms_question_idx on public.rooms(question_id);
create index if not exists players_room_idx on public.players(room_id);
create index if not exists hands_room_idx on public.hands(room_id);
create index if not exists hands_answer_idx on public.hands(answer_id);
create index if not exists used_answers_answer_idx on public.used_answers(answer_id);
create index if not exists submissions_player_idx on public.submissions(player_id);
create index if not exists submissions_answer_idx on public.submissions(answer_id);
create index if not exists rooms_created_by_hash_recent_idx on public.rooms(created_by_hash, created_at) where created_by_hash is not null;
create index if not exists players_joined_by_hash_recent_idx on public.players(joined_by_hash, created_at) where joined_by_hash is not null;

alter table public.questions enable row level security;
alter table public.answers enable row level security;
alter table public.rooms enable row level security;
alter table public.players enable row level security;
alter table public.hands enable row level security;
alter table public.used_answers enable row level security;
alter table public.submissions enable row level security;
alter table public.app_settings enable row level security;

revoke all on table public.questions, public.answers, public.rooms, public.players,
  public.hands, public.used_answers, public.submissions, public.app_settings
from anon, authenticated;

insert into public.app_settings(key, value)
values ('rate_pepper', gen_random_uuid()::text)
on conflict (key) do nothing;

create or replace function public._client_hash()
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare headers jsonb; ip text; pepper text;
begin
  begin
    headers := nullif(current_setting('request.headers', true), '')::jsonb;
  exception when others then headers := null;
  end;
  if headers is null then return null; end if;
  ip := nullif(btrim(split_part(coalesce(headers->>'x-forwarded-for', headers->>'cf-connecting-ip', ''), ',', 1)), '');
  if ip is null then return null; end if;
  select value into pepper from public.app_settings where key='rate_pepper';
  if pepper is null then return null; end if;
  return encode(extensions.digest(pepper || ':' || ip, 'sha256'), 'hex');
end
$$;

create or replace function public._is_admin(p_password text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare stored_hash text; ok boolean := false; cost integer := 0; client_hash text;
begin
  client_hash := coalesce(public._client_hash(), 'no-request-context');
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('bmp-admin:' || client_hash, 0));
  select value into stored_hash from public.app_settings where key='admin_hash' for update;
  if stored_hash is not null then ok := stored_hash = extensions.crypt(coalesce(p_password,''), stored_hash); end if;
  if not coalesce(ok,false) then perform pg_catalog.pg_sleep(1.5); return false; end if;
  begin cost := split_part(stored_hash,'$',3)::integer; exception when others then cost := 0; end;
  if cost < 10 then
    update public.app_settings set value=extensions.crypt(p_password, extensions.gen_salt('bf',10)) where key='admin_hash';
  end if;
  return true;
end
$$;

create or replace function public._clean_card(p_kind text, p_text text)
returns text
language plpgsql
immutable
set search_path = ''
as $$
declare t text; n int;
begin
  t := regexp_replace(trim(coalesce(p_text, '')), '\s+', ' ', 'g');
  if p_kind='q' then
    t := regexp_replace(t, '_{2,}', '____', 'g');
    if length(t)<5 then raise exception 'La question est trop courte.'; end if;
    if length(t)>150 then raise exception 'La question dépasse 150 caractères.'; end if;
    n := (length(t)-length(replace(t,'____','')))/4;
    if n=0 then raise exception 'Ajoute un trou « ____ » à l''endroit de la réponse.'; end if;
    if n>1 then raise exception 'Une question ne peut contenir qu''un seul trou.'; end if;
  else
    t := regexp_replace(t, '[.]+$', '');
    if length(t)<1 then raise exception 'La réponse est vide.'; end if;
    if length(t)>80 then raise exception 'La réponse dépasse 80 caractères.'; end if;
    if position('____' in t)>0 then raise exception 'Une réponse ne contient pas de trou.'; end if;
    t := upper(left(t,1)) || substr(t,2);
  end if;
  return t;
end
$$;

create or replace function public._check_card_rate()
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select count(*) from public.questions where added_by is not null and created_at > now()-interval '10 minutes')
   + (select count(*) from public.answers where added_by is not null and created_at > now()-interval '10 minutes') >= 60 then
    raise exception 'Trop de cartes ajoutées d''un coup. Réessaie dans quelques minutes.';
  end if;
end
$$;

create or replace function public._new_code()
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare c text; chars text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
begin
  loop
    c := '';
    for i in 1..4 loop c := c || substr(chars, 1 + floor(random()*length(chars))::int, 1); end loop;
    exit when not exists(select 1 from public.rooms where code=c);
  end loop;
  return c;
end
$$;

create or replace function public._player(p_code text, p_token uuid)
returns public.players
language sql
stable
security definer
set search_path = ''
as $$
  select p.* from public.players p join public.rooms r on r.id=p.room_id
  where r.code=upper(trim(p_code)) and p.token=p_token and p.active
$$;

create or replace function public._next_reader(p_room uuid, p_after uuid)
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    (select id from public.players where room_id=p_room and active
      and seat>coalesce((select seat from public.players where id=p_after),-1) order by seat limit 1),
    (select id from public.players where room_id=p_room and active order by seat limit 1))
$$;

create or replace function public._draw_question(p_room uuid)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare q int; used int[];
begin
  select used_questions into used from public.rooms where id=p_room;
  select id into q from public.questions where deleted_at is null and not(id=any(used)) order by random() limit 1;
  if q is null then
    used := '{}';
    select id into q from public.questions where deleted_at is null order by random() limit 1;
  end if;
  update public.rooms set used_questions=used||q where id=p_room;
  return q;
end
$$;

create or replace function public._deal(p_room uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare pl record; need int; hs int; avail int;
begin
  select hand_size into hs from public.rooms where id=p_room;
  for pl in select id from public.players where room_id=p_room and active order by seat loop
    select hs-count(*) into need from public.hands where player_id=pl.id;
    if need>0 then
      select count(*) into avail from public.answers a where a.deleted_at is null
        and not exists(select 1 from public.used_answers u where u.room_id=p_room and u.answer_id=a.id);
      if avail<need then
        delete from public.used_answers u where u.room_id=p_room
          and not exists(select 1 from public.hands h where h.room_id=p_room and h.answer_id=u.answer_id);
      end if;
      insert into public.hands(player_id,answer_id,room_id)
      select pl.id,a.id,p_room from public.answers a where a.deleted_at is null
        and not exists(select 1 from public.used_answers u where u.room_id=p_room and u.answer_id=a.id)
      order by random() limit need;
      insert into public.used_answers(room_id,answer_id)
      select p_room,h.answer_id from public.hands h where h.player_id=pl.id on conflict do nothing;
    end if;
  end loop;
end
$$;

create or replace function public._maybe_judge(p_room uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare r public.rooms;
begin
  select * into r from public.rooms where id=p_room;
  if r.status<>'answering' then return; end if;
  if not exists(
    select 1 from public.players p where p.room_id=p_room and p.active and p.id<>r.reader_id
      and not exists(select 1 from public.submissions s where s.room_id=p_room and s.round=r.round and s.player_id=p.id)
  ) and exists(select 1 from public.submissions s where s.room_id=p_room and s.round=r.round) then
    update public.rooms set status='judging',updated_at=now() where id=p_room;
  end if;
end
$$;

create or replace function public._start_round(p_room uuid, p_reader uuid, p_next_round integer)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare q int;
begin
  perform public._deal(p_room);
  q := public._draw_question(p_room);
  update public.rooms set status='answering',round=p_next_round,reader_id=p_reader,question_id=q,
    winner_id=null,winning_submission_id=null,skips_used=0,updated_at=now() where id=p_room;
end
$$;

create or replace function public._remove_player(p_player uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare pl public.players; r public.rooms; nr uuid;
begin
  select * into pl from public.players where id=p_player;
  if pl.id is null or not pl.active then return; end if;
  select * into r from public.rooms where id=pl.room_id for update;
  update public.players set active=false where id=p_player;
  delete from public.hands where player_id=p_player;
  if r.host_id=p_player then
    update public.rooms set host_id=(select id from public.players where room_id=r.id and active order by seat limit 1) where id=r.id;
  end if;
  if r.status in ('answering','judging','reveal') then
    if (select count(*) from public.players where room_id=r.id and active)<3 then
      if r.status<>'reveal' then
        insert into public.hands(player_id,answer_id,room_id)
        select s.player_id,s.answer_id,r.id from public.submissions s join public.players p on p.id=s.player_id and p.active
        where s.room_id=r.id and s.round=r.round on conflict do nothing;
        delete from public.submissions where room_id=r.id and round=r.round;
      end if;
      update public.rooms set status='lobby',updated_at=now() where id=r.id;
    elsif r.reader_id=p_player then
      nr := public._next_reader(r.id,p_player);
      if r.status<>'reveal' then
        insert into public.hands(player_id,answer_id,room_id)
        select s.player_id,s.answer_id,r.id from public.submissions s join public.players p on p.id=s.player_id and p.active
        where s.room_id=r.id and s.round=r.round on conflict do nothing;
        delete from public.submissions where room_id=r.id and round=r.round;
      end if;
      perform public._start_round(r.id,nr,r.round+1);
    elsif r.status in ('answering','judging') then
      delete from public.submissions where room_id=r.id and round=r.round and player_id=p_player;
      if r.status='judging' and not exists(select 1 from public.submissions where room_id=r.id and round=r.round) then
        update public.rooms set status='answering',updated_at=now() where id=r.id;
      elsif r.status='answering' then perform public._maybe_judge(r.id); end if;
    end if;
  end if;
  update public.rooms set updated_at=now() where id=r.id;
end
$$;

create or replace function public.add_question(p_text text, p_author text default null)
returns json
language plpgsql
security definer
set search_path = ''
as $$
declare t text; q public.questions;
begin
  t := public._clean_card('q',p_text);
  select * into q from public.questions where lower(text)=lower(t);
  if q.id is not null and q.deleted_at is null then raise exception 'Cette question existe déjà.'; end if;
  perform public._check_card_rate();
  if q.id is not null then update public.questions set deleted_at=null,text=t where id=q.id returning * into q;
  else insert into public.questions(text,added_by) values(t,coalesce(nullif(left(trim(p_author),20),''),'anonyme')) returning * into q; end if;
  return json_build_object('id',q.id,'text',q.text,'total',(select count(*) from public.questions where deleted_at is null));
end
$$;

create or replace function public.add_answer(p_text text, p_author text default null)
returns json
language plpgsql
security definer
set search_path = ''
as $$
declare t text; a public.answers;
begin
  t := public._clean_card('a',p_text);
  select * into a from public.answers where lower(text)=lower(t);
  if a.id is not null and a.deleted_at is null then raise exception 'Cette réponse existe déjà.'; end if;
  perform public._check_card_rate();
  if a.id is not null then update public.answers set deleted_at=null,text=t where id=a.id returning * into a;
  else insert into public.answers(text,added_by) values(t,coalesce(nullif(left(trim(p_author),20),''),'anonyme')) returning * into a; end if;
  return json_build_object('id',a.id,'text',a.text,'total',(select count(*) from public.answers where deleted_at is null));
end
$$;

