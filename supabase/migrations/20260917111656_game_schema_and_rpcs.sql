create or replace function public.create_room(p_name text, p_target integer default 5)
returns json
language plpgsql
security definer
set search_path = ''
as $$
declare r public.rooms; p public.players; n text:=left(trim(coalesce(p_name,'')),20); client_hash text; attempt integer;
begin
  if n='' then raise exception 'Choisis un pseudo.'; end if;
  if p_target is null or p_target not in(3,5,7,10) then raise exception 'Le score cible doit être 3, 5, 7 ou 10.'; end if;
  client_hash:=public._client_hash();
  if client_hash is not null then
    perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('bmp-create:'||client_hash,0));
    if (select count(*) from public.rooms where created_by_hash=client_hash and created_at>now()-interval '10 minutes')>=10 then
      raise exception 'Trop de parties créées récemment. Réessaie dans quelques minutes.';
    end if;
  end if;
  delete from public.rooms where updated_at<now()-interval '1 day';
  for attempt in 1..5 loop
    begin insert into public.rooms(code,target_score,created_by_hash) values(public._new_code(),p_target,client_hash) returning * into r; exit;
    exception when unique_violation then if attempt=5 then raise exception 'Impossible de générer un code de partie. Réessaie.'; end if; end;
  end loop;
  insert into public.players(room_id,name,seat,joined_by_hash) values(r.id,n,0,client_hash) returning * into p;
  update public.rooms set host_id=p.id where id=r.id;
  return json_build_object('code',r.code,'player_id',p.id,'token',p.token);
end
$$;

create or replace function public.join_room(p_code text, p_name text)
returns json
language plpgsql
security definer
set search_path = ''
as $$
declare r public.rooms; p public.players; n text:=left(trim(coalesce(p_name,'')),20); client_hash text;
begin
  if n='' then raise exception 'Choisis un pseudo.'; end if;
  client_hash:=public._client_hash();
  if client_hash is not null then
    perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('bmp-join:'||client_hash,0));
    if (select count(*) from public.players where joined_by_hash=client_hash and created_at>now()-interval '10 minutes')>=30 then
      raise exception 'Trop de tentatives de connexion récentes. Réessaie dans quelques minutes.';
    end if;
  end if;
  select * into r from public.rooms where code=upper(trim(p_code)) for update;
  if r.id is null then if client_hash is not null then perform pg_catalog.pg_sleep(0.15); end if; raise exception 'Aucune partie avec ce code.'; end if;
  if (select count(*) from public.players where room_id=r.id and active)>=12 then raise exception 'La partie est pleine (12 joueurs max).'; end if;
  if exists(select 1 from public.players where room_id=r.id and active and lower(name)=lower(n)) then raise exception 'Ce pseudo est déjà pris dans cette partie.'; end if;
  insert into public.players(room_id,name,seat,joined_by_hash)
  values(r.id,n,(select coalesce(max(seat),-1)+1 from public.players where room_id=r.id),client_hash) returning * into p;
  if r.status<>'lobby' then perform public._deal(r.id); end if;
  update public.rooms set updated_at=now() where id=r.id;
  return json_build_object('code',r.code,'player_id',p.id,'token',p.token);
end
$$;

create or replace function public.get_state(p_code text, p_token uuid)
returns json
language plpgsql
security definer
set search_path = ''
as $$
declare me public.players; r public.rooms;
begin
  me:=public._player(p_code,p_token); if me.id is null then raise exception 'Session expirée. Rejoins la partie à nouveau.'; end if;
  if me.last_seen<now()-interval '5 minutes' then update public.players set last_seen=now() where id=me.id; end if;
  select * into r from public.rooms where id=me.room_id;
  return json_build_object(
    'room',json_build_object('code',r.code,'status',r.status,'round',r.round,'target',r.target_score,'host_id',r.host_id,'reader_id',r.reader_id,'winner_id',r.winner_id,'winning_submission_id',r.winning_submission_id,'updated_at',r.updated_at,'skips_left',3-r.skips_used,'reward_used',r.reward_used,'reward_kind',r.reward_kind,'reward_text',r.reward_text,'submission_count',(select count(*) from public.submissions s where s.room_id=r.id and s.round=r.round)),
    'me',json_build_object('id',me.id,'name',me.name,'can_discard',r.status='answering' and r.reader_id<>me.id and me.discard_round<>r.round and not exists(select 1 from public.submissions s where s.room_id=r.id and s.round=r.round and s.player_id=me.id)),
    'question',(select text from public.questions where id=r.question_id),
    'players',(select coalesce(json_agg(json_build_object('id',p.id,'name',p.name,'score',p.score,'active',p.active,'submitted',exists(select 1 from public.submissions s where s.room_id=r.id and s.round=r.round and s.player_id=p.id)) order by p.seat),'[]'::json) from public.players p where p.room_id=r.id and (p.active or (r.status in('reveal','finished') and p.id=r.winner_id))),
    'hand',(select coalesce(json_agg(json_build_object('id',a.id,'text',a.text) order by a.text),'[]'::json) from public.hands h join public.answers a on a.id=h.answer_id where h.player_id=me.id),
    'my_submission',(select a.text from public.submissions s join public.answers a on a.id=s.answer_id where s.room_id=r.id and s.round=r.round and s.player_id=me.id),
    'submissions',case when r.status in('reveal','finished') or (r.status='judging' and r.reader_id=me.id) then
      (select coalesce(json_agg(json_build_object('id',s.id,'text',a.text,'author',case when r.status in('reveal','finished') then p.name end) order by s.sort_key),'[]'::json) from public.submissions s join public.answers a on a.id=s.answer_id join public.players p on p.id=s.player_id where s.room_id=r.id and s.round=r.round)
      else '[]'::json end);
end
$$;

create or replace function public.start_game(p_code text,p_token uuid)
returns void language plpgsql security definer set search_path='' as $$
declare me public.players; r public.rooms;
begin
  me:=public._player(p_code,p_token); if me.id is null then raise exception 'Session expirée. Rejoins la partie à nouveau.'; end if;
  select * into r from public.rooms where id=me.room_id for update;
  if r.host_id<>me.id then raise exception 'Seul l''hôte peut lancer la partie.'; end if;
  if r.status not in('lobby','finished') then raise exception 'La partie est déjà en cours.'; end if;
  if (select count(*) from public.players where room_id=r.id and active)<3 then raise exception 'Il faut au moins 3 joueurs.'; end if;
  if r.status='finished' then
    update public.players set score=0,discard_round=0 where room_id=r.id;
    delete from public.hands where room_id=r.id; delete from public.used_answers where room_id=r.id; delete from public.submissions where room_id=r.id;
    update public.rooms set used_questions='{}',round=0,reward_used=false,reward_kind=null,reward_text=null where id=r.id; r.round:=0;
  end if;
  perform public._start_round(r.id,public._next_reader(r.id,r.reader_id),r.round+1);
end $$;

create or replace function public.submit_answer(p_code text,p_token uuid,p_answer_id integer)
returns void language plpgsql security definer set search_path='' as $$
declare me public.players; r public.rooms;
begin
  me:=public._player(p_code,p_token); if me.id is null then raise exception 'Session expirée. Rejoins la partie à nouveau.'; end if;
  select * into r from public.rooms where id=me.room_id for update;
  if r.status<>'answering' then raise exception 'Les réponses sont fermées pour ce tour.'; end if;
  if r.reader_id=me.id then raise exception 'Tu lis la question ce tour-ci.'; end if;
  if exists(select 1 from public.submissions where room_id=r.id and round=r.round and player_id=me.id) then raise exception 'Tu as déjà joué une carte.'; end if;
  if not exists(select 1 from public.hands where player_id=me.id and answer_id=p_answer_id) then raise exception 'Cette carte n''est pas dans ta main.'; end if;
  insert into public.submissions(room_id,round,player_id,answer_id) values(r.id,r.round,me.id,p_answer_id);
  delete from public.hands where player_id=me.id and answer_id=p_answer_id;
  perform public._deal(r.id); perform public._maybe_judge(r.id); update public.rooms set updated_at=now() where id=r.id;
end $$;

create or replace function public.discard_card(p_code text,p_token uuid,p_answer_id integer)
returns void language plpgsql security definer set search_path='' as $$
declare me public.players; r public.rooms;
begin
  me:=public._player(p_code,p_token); if me.id is null then raise exception 'Session expirée. Rejoins la partie à nouveau.'; end if;
  select * into r from public.rooms where id=me.room_id for update;
  if r.status<>'answering' then raise exception 'Tu ne peux échanger une carte que pendant les réponses.'; end if;
  if r.reader_id=me.id then raise exception 'Tu lis la question ce tour-ci.'; end if;
  if exists(select 1 from public.submissions where room_id=r.id and round=r.round and player_id=me.id) then raise exception 'Tu as déjà joué une carte ce tour-ci.'; end if;
  if me.discard_round=r.round then raise exception 'Tu as déjà échangé une carte ce tour-ci.'; end if;
  if not exists(select 1 from public.hands where player_id=me.id and answer_id=p_answer_id) then raise exception 'Cette carte n''est pas dans ta main.'; end if;
  delete from public.hands where player_id=me.id and answer_id=p_answer_id;
