create or replace function public._white_speaker(p_room uuid)
returns uuid language sql stable security definer set search_path to '' as $fn$
  select p.id from public.rooms r
  join public.players p on p.room_id=r.id and p.active
  join public.white_roles wr on wr.room_id=r.id and wr.round=r.round and wr.player_id=p.id and not wr.eliminated
  join public.players origin on origin.id=r.reader_id
  where r.id=p_room and r.status='white_clue'
    and not exists(select 1 from public.white_clues c
      where c.room_id=r.id and c.round=r.round and c.cycle=r.white_cycle and c.player_id=p.id)
  order by (p.seat - origin.seat + 10000) % 10000 limit 1
$fn$;

create or replace function public._white_finish(p_room uuid,p_winner text)
returns void language plpgsql security definer set search_path to '' as $fn$
declare r public.rooms;
begin
  select * into r from public.rooms where id=p_room for update;
  if r.mode<>'white' or r.status not in ('white_clue','white_vote','white_guess') then return; end if;
  if p_winner not in ('civils','imposteurs','white') then raise exception 'Équipe inconnue.'; end if;
  update public.white_rounds set winner=p_winner where room_id=p_room and round=r.round;
  update public.players p set score=p.score+
    case when p_winner='civils' and wr.role='civil' then 2
         when p_winner='white' and wr.role='white' then 3
         when p_winner='imposteurs' and wr.role in ('white','undercover') and not wr.eliminated then 3
         else 0 end
  from public.white_roles wr
  where wr.room_id=p_room and wr.round=r.round and wr.player_id=p.id and p.active;
  update public.rooms set status='reveal',white_note=case p_winner
    when 'white' then 'Mr White a trouvé le mot !'
    when 'civils' then 'Les Civils ont démasqué les imposteurs.'
    else 'Les imposteurs remportent la manche.' end,
    phase_at=now(),updated_at=now() where id=p_room;
end $fn$;

create or replace function public._white_check_end(p_room uuid)
returns void language plpgsql security definer set search_path to '' as $fn$
declare r public.rooms; nc integer; ni integer;
begin
  select * into r from public.rooms where id=p_room for update;
  select count(*) filter (where wr.role='civil'),count(*) filter (where wr.role<>'civil')
    into nc,ni from public.white_roles wr join public.players p on p.id=wr.player_id and p.active
    where wr.room_id=p_room and wr.round=r.round and not wr.eliminated;
  if ni=0 then
    perform public._white_finish(p_room,'civils');
  elsif nc<=ni then
    perform public._white_finish(p_room,'imposteurs');
  else
    update public.rooms set status='white_clue',white_cycle=white_cycle+1,phase_at=now(),updated_at=now() where id=p_room;
  end if;
end $fn$;

create or replace function public._begin_white_round(p_room uuid,p_next_round integer)
returns void language plpgsql security definer set search_path to '' as $fn$
declare r public.rooms; c public.white_words; n integer; wid uuid; uid uuid; champ uuid;
begin
  select * into r from public.rooms where id=p_room for update;
  if p_next_round>r.target_score then
    select id into champ from public.players where room_id=p_room and active order by score desc,seat limit 1;
    update public.rooms set status='finished',winner_id=champ,phase_at=now(),updated_at=now() where id=p_room;
    return;
  end if;
  if p_next_round=1 then
    delete from public.white_rounds where room_id=p_room;
    update public.rooms set white_used_words='{}' where id=p_room;
    r.white_used_words:='{}';
  end if;
  select * into c from public.white_words
   where deleted_at is null and not (id=any(r.white_used_words)) order by random() limit 1;
  if c.id is null then
    select * into c from public.white_words where deleted_at is null order by random() limit 1;
    update public.rooms set white_used_words='{}' where id=p_room;
  end if;
  if c.id is null then raise exception 'Aucune paire de mots Mr White disponible.'; end if;
  select count(*) into n from public.players where room_id=p_room and active;
  if n<3 then raise exception 'Mr White demande au moins 3 joueurs.'; end if;
  select id into wid from public.players where room_id=p_room and active order by random() limit 1;
  if n>=4 then
    select id into uid from public.players where room_id=p_room and active and id<>wid order by random() limit 1;
  end if;
  insert into public.white_rounds(room_id,round,word_id,civil_word,undercover_word)
  values(p_room,p_next_round,c.id,c.civil,c.undercover);
  insert into public.white_roles(room_id,round,player_id,role)
  select p_room,p_next_round,p.id,
   case when p.id=wid then 'white' when p.id=uid then 'undercover' else 'civil' end
  from public.players p where p.room_id=p_room and p.active;
  update public.players set next_ack_round=0 where room_id=p_room and active;
  update public.rooms set status='white_clue',round=p_next_round,
    previous_reader_id=reader_id,reader_id=(select id from public.players where room_id=p_room and active order by random() limit 1),
    white_cycle=1,white_note=null,white_used_words=white_used_words||c.id,
    question_id=null,question_choices='{}',winner_id=null,winning_submission_id=null,
    phase_at=now(),updated_at=now() where id=p_room;
end $fn$;

create or replace function public.white_state(p_code text,p_token uuid)
returns json language plpgsql security definer set search_path to '' as $fn$
declare me public.players; r public.rooms; w public.white_rounds; mine public.white_roles;
begin
  me:=public._player(p_code,p_token);
  if me.id is null then raise exception 'Session expirée. Rejoins la partie à nouveau.'; end if;
  select * into r from public.rooms where id=me.room_id;
  if r.mode<>'white' then raise exception 'Ce salon ne joue pas à Mr White.'; end if;
  if r.status='lobby' then return json_build_object('phase','lobby'); end if;
  select * into w from public.white_rounds where room_id=r.id and round=r.round;
  select * into mine from public.white_roles where room_id=r.id and round=r.round and player_id=me.id;
  return json_build_object(
    'phase',r.status,'cycle',r.white_cycle,'note',r.white_note,'role',mine.role,
    'word',case when mine.role='civil' then w.civil_word when mine.role='undercover' then w.undercover_word end,
    'eliminated',coalesce(mine.eliminated,false),
    'speaker_id',case when r.status='white_clue' then public._white_speaker(r.id) end,
    'has_clue',exists(select 1 from public.white_clues c where c.room_id=r.id and c.round=r.round and c.cycle=r.white_cycle and c.player_id=me.id),
    'voted',exists(select 1 from public.white_votes v where v.room_id=r.id and v.round=r.round and v.cycle=r.white_cycle and v.player_id=me.id),
    'bot_pending',case when r.status='white_clue' then
      exists(select 1 from public.players p where p.id=public._white_speaker(r.id) and p.is_bot and p.active)
      when r.status='white_vote' then
      exists(select 1 from public.players p join public.white_roles wr on wr.player_id=p.id and wr.room_id=r.id and wr.round=r.round
        where p.room_id=r.id and p.active and p.is_bot and not wr.eliminated
          and not exists(select 1 from public.white_votes v where v.room_id=r.id and v.round=r.round and v.cycle=r.white_cycle and v.player_id=p.id))
      when r.status='white_guess' then
      exists(select 1 from public.players p join public.white_roles wr on wr.player_id=p.id and wr.room_id=r.id and wr.round=r.round
        join public.white_rounds w on w.room_id=r.id and w.round=r.round
        where p.room_id=r.id and p.active and p.is_bot and wr.role='white' and wr.eliminated and w.last_eliminated=p.id)
      else false end,
    'votes_count',(select count(*) from public.white_votes v where v.room_id=r.id and v.round=r.round and v.cycle=r.white_cycle),
    'clues',(select coalesce(json_agg(json_build_object('player_id',c.player_id,'text',c.clue) order by c.created_at),'[]'::json)
             from public.white_clues c where c.room_id=r.id and c.round=r.round and c.cycle=r.white_cycle),
    'roles',(select coalesce(json_agg(json_build_object('player_id',wr.player_id,
      'voted',exists(select 1 from public.white_votes v where v.room_id=wr.room_id and v.round=wr.round
        and v.cycle=r.white_cycle and v.player_id=wr.player_id),
      'out',wr.eliminated,'role',case when wr.eliminated or r.status in ('reveal','finished') then wr.role end,
      'voted',exists(select 1 from public.white_votes v where v.room_id=r.id and v.round=r.round
        and v.cycle=r.white_cycle and v.player_id=wr.player_id))
      order by p.seat),'[]'::json)
      from public.white_roles wr join public.players p on p.id=wr.player_id
      where wr.room_id=r.id and wr.round=r.round),
    'last_eliminated',w.last_eliminated,'winner',w.winner,'guess_correct',w.guess_correct,
    'civil_word',case when r.status in ('reveal','finished') then w.civil_word end,
    'undercover_word',case when r.status in ('reveal','finished') then w.undercover_word end
  );
end $fn$;

create or replace function public.white_clue(p_code text,p_token uuid,p_clue text)
returns void language plpgsql security definer set search_path to '' as $fn$
declare me public.players; r public.rooms; clue text:=btrim(regexp_replace(coalesce(p_clue,''),'\s+',' ','g'));
begin
  me:=public._player(p_code,p_token);
  if me.id is null then raise exception 'Session expirée. Rejoins la partie à nouveau.'; end if;
  select * into r from public.rooms where id=me.room_id for update;
  if r.mode<>'white' or r.status<>'white_clue' then raise exception 'Ce n’est pas le tour des indices.'; end if;
  if me.id is distinct from public._white_speaker(r.id) then raise exception 'Ce n’est pas encore ton tour.'; end if;
  if length(clue) not between 2 and 100 then raise exception 'Indice de 2 à 100 caractères.'; end if;
  insert into public.white_clues(room_id,round,cycle,player_id,clue) values(r.id,r.round,r.white_cycle,me.id,clue);
  if public._white_speaker(r.id) is null then
    update public.rooms set status='white_vote',white_note=null,phase_at=now(),updated_at=now() where id=r.id;
  else update public.rooms set updated_at=now() where id=r.id; end if;
end $fn$;

create or replace function public._white_resolve_vote(p_room uuid)
returns void language plpgsql security definer set search_path to '' as $fn$
declare r public.rooms; out_id uuid; out_role text; nmax integer; ties integer; out_name text;
begin
  select * into r from public.rooms where id=p_room for update;
  if r.status<>'white_vote' then return; end if;
  if exists(select 1 from public.white_roles wr join public.players p on p.id=wr.player_id and p.active
      where wr.room_id=p_room and wr.round=r.round and not wr.eliminated and
      not exists(select 1 from public.white_votes v where v.room_id=p_room and v.round=r.round and
        v.cycle=r.white_cycle and v.player_id=wr.player_id)) then return; end if;
  select max(n) into nmax from (select count(*) n from public.white_votes v
    where v.room_id=p_room and v.round=r.round and v.cycle=r.white_cycle group by target_id) z;
  select count(*) into ties from (select target_id,count(*) n from public.white_votes
    where room_id=p_room and round=r.round and cycle=r.white_cycle group by target_id) z where n=nmax;
  if nmax is null or ties<>1 then
    update public.rooms set status='white_clue',white_cycle=white_cycle+1,white_note='Égalité : personne n’est éliminé. Nouveau tour d’indices.',
      phase_at=now(),updated_at=now() where id=p_room;
    return;
  end if;
  select v.target_id into out_id from public.white_votes v
    where v.room_id=p_room and v.round=r.round and v.cycle=r.white_cycle
    group by v.target_id order by count(*) desc limit 1;
  update public.white_roles set eliminated=true,eliminated_cycle=r.white_cycle
    where room_id=p_room and round=r.round and player_id=out_id returning role into out_role;
  select name into out_name from public.players where id=out_id;
  update public.white_rounds set last_eliminated=out_id where room_id=p_room and round=r.round;
  update public.rooms set white_note=out_name||' est éliminé ('||
    case out_role when 'civil' then 'Civil' when 'undercover' then 'Undercover' else 'Mr White' end||').',
    updated_at=now() where id=p_room;
  if out_role='white' then
    update public.rooms set status='white_guess',phase_at=now(),updated_at=now() where id=p_room;
  else perform public._white_check_end(p_room); end if;
end $fn$;

create or replace function public.white_vote(p_code text,p_token uuid,p_target uuid)
returns void language plpgsql security definer set search_path to '' as $fn$
declare me public.players; r public.rooms;
begin
  me:=public._player(p_code,p_token);
  if me.id is null then raise exception 'Session expirée. Rejoins la partie à nouveau.'; end if;
  select * into r from public.rooms where id=me.room_id for update;
  if r.mode<>'white' or r.status<>'white_vote' then raise exception 'Le vote est fermé.'; end if;
  if not exists(select 1 from public.white_roles where room_id=r.id and round=r.round and player_id=me.id and not eliminated)
  then raise exception 'Tu es éliminé.'; end if;
  if p_target=me.id or not exists(select 1 from public.white_roles wr join public.players p on p.id=wr.player_id and p.active
        where wr.room_id=r.id and wr.round=r.round and wr.player_id=p_target and not wr.eliminated)
  then raise exception 'Cible de vote invalide.'; end if;
  insert into public.white_votes(room_id,round,cycle,player_id,target_id) values(r.id,r.round,r.white_cycle,me.id,p_target);
  perform public._white_resolve_vote(r.id);
  update public.rooms set updated_at=now() where id=r.id;
end $fn$;

create or replace function public.white_guess(p_code text,p_token uuid,p_word text)
returns void language plpgsql security definer set search_path to '' as $fn$
declare me public.players; r public.rooms; expected text; good boolean;
begin
  me:=public._player(p_code,p_token);
  if me.id is null then raise exception 'Session expirée. Rejoins la partie à nouveau.'; end if;
  select * into r from public.rooms where id=me.room_id for update;
  if r.mode<>'white' or r.status<>'white_guess' then raise exception 'La tentative est terminée.'; end if;
  if not exists(select 1 from public.white_roles wr join public.white_rounds w on w.room_id=wr.room_id and w.round=wr.round
    where wr.room_id=r.id and wr.round=r.round and wr.player_id=me.id and wr.role='white' and wr.eliminated
      and w.last_eliminated=me.id) then raise exception 'Seul Mr White peut tenter de deviner.'; end if;
  select civil_word into expected from public.white_rounds where room_id=r.id and round=r.round;
  if length(btrim(coalesce(p_word,''))) not between 1 and 60 then raise exception 'Propose un mot.'; end if;
  good:=lower(btrim(regexp_replace(p_word,'\s+',' ','g')))=lower(btrim(expected));
  update public.white_rounds set guess_correct=good where room_id=r.id and round=r.round;
  if good then perform public._white_finish(r.id,'white');
  else
    update public.rooms set white_note='Mr White n’a pas trouvé le mot. La partie continue.',updated_at=now() where id=r.id;
    perform public._white_check_end(r.id);
  end if;
end $fn$;

create or replace function public.white_depart(p_room uuid,p_player uuid)
returns void language plpgsql security definer set search_path to '' as $fn$
declare r public.rooms;
begin
  select * into r from public.rooms where id=p_room for update;
  if r.mode<>'white' or r.status not in ('white_clue','white_vote','white_guess') then return; end if;
  update public.white_roles set eliminated=true where room_id=p_room and round=r.round and player_id=p_player;
  delete from public.white_votes where room_id=p_room and round=r.round and cycle=r.white_cycle
    and (player_id=p_player or target_id=p_player);
  if (select count(*) from public.players where room_id=p_room and active)<3 then
    update public.rooms set status='lobby',white_note=null,phase_at=now(),updated_at=now() where id=p_room;
    return;
  end if;
  -- Un départ ne doit pas effacer les indices ou les votes du tour en cours.
  -- On termine seulement si les équipes ont effectivement atteint la condition de fin.
  if not exists (
      select 1 from public.white_roles wr join public.players p on p.id=wr.player_id and p.active
      where wr.room_id=p_room and wr.round=r.round and not wr.eliminated and wr.role<>'civil'
    ) or (
      (select count(*) from public.white_roles wr join public.players p on p.id=wr.player_id and p.active
       where wr.room_id=p_room and wr.round=r.round and not wr.eliminated and wr.role='civil')
      <=
      (select count(*) from public.white_roles wr join public.players p on p.id=wr.player_id and p.active
       where wr.room_id=p_room and wr.round=r.round and not wr.eliminated and wr.role<>'civil')
    ) then
    perform public._white_check_end(p_room);
  elsif r.status='white_guess' then
    perform public._white_check_end(p_room);
  elsif r.status='white_clue' then
    if public._white_speaker(p_room) is null then
      update public.rooms set status='white_vote',phase_at=now(),updated_at=now() where id=p_room;
    end if;
  else
    perform public._white_resolve_vote(p_room);
  end if;
end $fn$;

create or replace function public.white_bot_step(p_code text,p_token uuid)
